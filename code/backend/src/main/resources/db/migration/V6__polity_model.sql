-- ==========================================================================
-- V6：历史政权（展示用）与事件—政权关联
--
-- 定位：M3 的「历史时空矩阵」需要一个可以按地区分组的政权维度。
--       这里只建**最小展示模型**——政权是一个带名称与可选存在区间的对象，
--       不做疆域多边形、不做王朝谱系、不做政权继承关系。
--
-- 设计要点：
--   1. region_code 是**展示分组**，不是历史疆域判定。跨区域政权按主要历史
--      地理归属取一个值，避免本阶段建设复杂的归属体系。
--   2. 存在区间（start/end）可选，且**不参与**矩阵过滤——矩阵只看事件时间，
--      政权是否显示取决于它在当前窗口内有没有事件。存在区间仅作展示与检索辅助。
--   3. 事件—政权多对多，(event_id, polity_id) 唯一，避免重复关联。
--   4. 删除语义：删事件 → 关联行随之消失（CASCADE）；删政权 → 关联行消失
--      （CASCADE），但**不会**删除事件本身——事件是独立史料对象。
--   5. 绝不根据事件名称或坐标自动推断政权归属：本表只存人工建立的关联。
-- 注：Flyway 已在事务中执行本脚本，故不再显式 BEGIN/COMMIT（否则触发 25001 警告）。
-- ==========================================================================

CREATE TABLE historical_polity (
    polity_id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             text        NOT NULL,
    name_lang        text,
    region_code      text        NOT NULL,
    start_year_astro integer,
    end_year_astro   integer,
    description      text,
    notes            text,
    record_status    text        NOT NULL DEFAULT 'staging',
    created_at       timestamptz NOT NULL DEFAULT now(),
    updated_at       timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT ck_polity_name_not_blank CHECK (btrim(name) <> ''),
    CONSTRAINT ck_polity_region CHECK (region_code IN (
        'east_asia', 'central_asia', 'south_asia', 'southeast_asia', 'middle_east',
        'europe', 'africa', 'north_america', 'south_america', 'oceania')),
    CONSTRAINT ck_polity_record_status CHECK (record_status IN ('staging', 'published', 'rejected')),
    -- 两端要么都填、要么都空；填了就必须 start <= end（天文学纪年整数）
    CONSTRAINT ck_polity_time_pair CHECK (
        (start_year_astro IS NULL) = (end_year_astro IS NULL)),
    CONSTRAINT ck_polity_time_order CHECK (
        start_year_astro IS NULL OR start_year_astro <= end_year_astro),
    CONSTRAINT uq_polity_name_region UNIQUE (name, region_code)
);

COMMENT ON TABLE historical_polity IS
    '历史政权（展示用最小模型）：按展示地区分组，仅用于 M3 时空矩阵的行维度';
COMMENT ON COLUMN historical_polity.region_code IS
    '展示分组，非历史疆域判定；跨区域政权取主要历史地理归属';
COMMENT ON COLUMN historical_polity.start_year_astro IS
    '可选的存在起始年（天文学纪年）；不参与矩阵过滤，仅作展示';

CREATE INDEX ix_polity_region ON historical_polity (region_code, name);
CREATE INDEX ix_polity_years ON historical_polity (start_year_astro, end_year_astro);

CREATE TABLE event_polity (
    event_polity_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id        bigint      NOT NULL,
    polity_id       bigint      NOT NULL,
    role            text,
    note            text,
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT fk_event_polity_event
        FOREIGN KEY (event_id) REFERENCES event (event_id) ON DELETE CASCADE,
    CONSTRAINT fk_event_polity_polity
        FOREIGN KEY (polity_id) REFERENCES historical_polity (polity_id) ON DELETE CASCADE,
    CONSTRAINT uq_event_polity UNIQUE (event_id, polity_id)
);

COMMENT ON TABLE event_polity IS
    '事件—政权关联（多对多）。仅存人工建立的关联，禁止按名称/坐标自动推断';

CREATE INDEX ix_event_polity_polity ON event_polity (polity_id);
CREATE INDEX ix_event_polity_event ON event_polity (event_id);

-- updated_at 统一由 V4 的触发器函数维护（clock_timestamp，同事务内也会前进）
CREATE TRIGGER trg_polity_touch
    BEFORE UPDATE ON historical_polity
    FOR EACH ROW EXECUTE FUNCTION fn_touch_updated_at();

CREATE TRIGGER trg_event_polity_touch
    BEFORE UPDATE ON event_polity
    FOR EACH ROW EXECUTE FUNCTION fn_touch_updated_at();

