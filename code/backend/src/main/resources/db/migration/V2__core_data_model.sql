    CONSTRAINT ck_hpn_association_certainty
        CHECK (association_certainty IN ('certain', 'less-certain', 'uncertain')),
    CONSTRAINT ck_hpn_time_bound_type
        CHECK (time_bound_type IN ('exact', 'bounded', 'exact_or_bounded', 'tpq_taq', 'derived_tpq_taq', 'snapshot', 'unknown')),
    CONSTRAINT ck_hpn_record_status CHECK (record_status IN ('staging', 'published', 'rejected')),
    CONSTRAINT ck_hpn_created_by CHECK (created_by IN ('import', 'manual')),

    -- C08（不得改成 UNIQUE(source_record_id)：一个记录最多 3 个名称行）
    CONSTRAINT uq_hpn_c08 UNIQUE (source_record_id, name_type, name_text, name_lang),
    -- C16
    CONSTRAINT ck_hpn_c16 CHECK (time_bound_type <> 'exact'
        OR (valid_from_year_astro IS NOT NULL AND valid_to_year_astro IS NOT NULL)),
    -- C25 / C26
    CONSTRAINT ck_hpn_c25 CHECK ((record_status = 'rejected') = (rejected_by IS NOT NULL)),
    CONSTRAINT ck_hpn_c26 CHECK (rejected_by IS NULL OR rejected_by IN ('auto', 'manual')),
    CONSTRAINT ck_hpn_manual_needs_manual_created_by CHECK (source_record_id IS NOT NULL OR created_by = 'manual'),
    -- BCP-47 形态（'und' 除外）
