-- =============================================================================
-- V2：核心数据模型（九张表 + 约束 + 索引）
-- 权威依据：设计资料/V2.1.1_正式交付/CORE_DATA_MODEL_V2.1.1.md
--   §2 通用约定 / §4 键策略 / §5.1–§5.9 表定义 / 附录 A 约束全集 C01–C29
-- 视图在 V3 单独建立（§5.10）。
--
-- 施工口径（与设计逐条对应，未自行增删字段）：
--   1. 主键全部 bigint identity，例外两个自然键：data_source.source_id / data_dataset.dataset_id（§2）。
--   2. 外键一律不级联删除（ON DELETE 默认 NO ACTION）——删除有影响提示，无静默级联（02_系统架构设计 §M2）。
--   3. 空间字段 WGS84 / EPSG:4326，GiST 索引；常用时间字段 B-tree（02_系统架构设计 §6）。
--   4. 设计文件未给 DEFAULT 的时间列一律不加 DEFAULT，由写入方显式提供（不擅自改变列语义）。
--   5. 约束命名带设计编号（c01/c03/…），便于与附录 A 逐条核对。
-- =============================================================================

-- -----------------------------------------------------------------------------
-- §5.1 data_source（6 列，删除许可相关 2 列后的保留列）
-- -----------------------------------------------------------------------------
CREATE TABLE data_source (
    source_id        text        NOT NULL,
    display_name     text        NOT NULL,
    homepage_url     text,
    display_priority smallint    NOT NULL DEFAULT 0,
    notes            text,
    created_at       timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT pk_data_source PRIMARY KEY (source_id),
    CONSTRAINT ck_data_source_source_id
        CHECK (source_id IN ('chgis', 'pleiades', 'whg', 'mcgd'))
);

COMMENT ON TABLE data_source IS '四个数据源。自然键 text 主键（§2 主键例外之一）。不含任何许可列（§7.1 许可门禁已废除）。';
COMMENT ON COLUMN data_source.homepage_url IS '是 homepage_url，不是暂存列名 homepage（后者已判 dropped）。';
COMMENT ON COLUMN data_source.display_priority IS '同地点多来源冲突时的展示排序；默认 0 = 全部等权 = 不启用。';

-- -----------------------------------------------------------------------------
-- §5.2 data_dataset（17 列，删除 9 列许可相关列后的保留列）
-- -----------------------------------------------------------------------------
CREATE TABLE data_dataset (
    dataset_id          text        NOT NULL,
    source_id           text        NOT NULL,
    display_name        text        NOT NULL,
    dataset_version     text,
    record_scopes       text[]      NOT NULL,
    place_grain         text        NOT NULL,
    location_grain      text        NOT NULL,
    grain_evidence      text,
    occurrence_key_rule text        NOT NULL,
    external_id_nature  text        NOT NULL,
    content_sha256      text,
    local_path          text,
    record_count        integer,
    is_active           boolean     NOT NULL DEFAULT true,
    notes               text,
    created_at          timestamptz NOT NULL,
    updated_at          timestamptz NOT NULL,

    CONSTRAINT pk_data_dataset PRIMARY KEY (dataset_id),
    CONSTRAINT fk_data_dataset_source FOREIGN KEY (source_id) REFERENCES data_source (source_id),

    -- §5.2 约束：array_length(record_scopes,1) >= 1
    -- 施工说明：字面式 array_length('{}',1) 返回 NULL，CHECK 遇 NULL 判为通过，
    --           会让空数组绕过「record_scopes 非空」（§8 第 1 条前置校验的本意）。
    --           此处用 coalesce 包一层，语义收紧为「确实非空」，不放松任何合法数据。
    CONSTRAINT ck_data_dataset_record_scopes
        CHECK (coalesce(array_length(record_scopes, 1), 0) >= 1),
    CONSTRAINT ck_data_dataset_place_grain
        CHECK (place_grain IN ('per_record', 'per_parent_external_id')),
    CONSTRAINT ck_data_dataset_location_grain
        CHECK (location_grain IN ('per_record', 'per_parent_external_id')),
    CONSTRAINT ck_data_dataset_occurrence_key_rule
        CHECK (occurrence_key_rule IN ('none', 'parent_ordinal')),
    CONSTRAINT ck_data_dataset_external_id_nature
        CHECK (external_id_nature IN ('source_declared', 'pipeline_composed')),
    CONSTRAINT ck_data_dataset_nature_vs_rule
        CHECK (external_id_nature <> 'pipeline_composed' OR occurrence_key_rule = 'none')
);

COMMENT ON TABLE data_dataset IS '七个数据集。自然键 text 主键。place_grain / location_grain 是 V2 既有列（非 V2.1.1 新增，§5.2.2）。';
COMMENT ON COLUMN data_dataset.record_scopes IS '取值应 ⊆ {place,name,location,edge}；值域校验属导入前置校验（§8 第 1 条），不做 DB CHECK。';
COMMENT ON COLUMN data_dataset.grain_evidence IS '该 grain 判定从哪几个数推出来的，必填（导入前置校验第 1 条之外的人工可核依据）。';
COMMENT ON COLUMN data_dataset.occurrence_key_rule IS '保留列；其服务对象 occurrence_key 已被 duplicate_ordinal 取代，本列不再参与键生成（§5.2.3）。';

-- -----------------------------------------------------------------------------
-- §5.3 import_batch（19 列）
-- -----------------------------------------------------------------------------
CREATE TABLE import_batch (
    batch_id                   bigint      GENERATED BY DEFAULT AS IDENTITY,
    dataset_id                 text        NOT NULL,
    dataset_version            text,
    derivation_version         text        NOT NULL,
    status                     text        NOT NULL,
    input_file                 text,
    input_sha256               text,
    input_row_count            integer,
    inserted_source_record_ids bigint[],
    updated_source_record_ids  bigint[],
    quarantined_count          integer     NOT NULL DEFAULT 0,
    skipped_count              integer,
    failed_count               integer,
    blocked_count              integer     NOT NULL DEFAULT 0,
    rollback_of_batch_id       bigint,
    started_at                 timestamptz,
    finished_at                timestamptz,
    operator                   text,
    notes                      text,

    CONSTRAINT pk_import_batch PRIMARY KEY (batch_id),
    CONSTRAINT fk_import_batch_dataset FOREIGN KEY (dataset_id) REFERENCES data_dataset (dataset_id),
    CONSTRAINT fk_import_batch_rollback_of FOREIGN KEY (rollback_of_batch_id) REFERENCES import_batch (batch_id),
    CONSTRAINT ck_import_batch_status
        CHECK (status IN ('running', 'succeeded', 'partial', 'failed', 'rolled_back', 'quarantined_only'))
);

COMMENT ON TABLE import_batch IS '导入批次。status 判据（§5.3）：succeeded=failed_count=0；partial=有失败且逐条有台账；failed=前置校验未通过或整批中断（此时一行都不许落库）；quarantined_only=inserted 0 且 quarantined=input_row_count。';
COMMENT ON COLUMN import_batch.quarantined_count IS '本批隔离记录数（is_active=false）。既不是 inserted 也不是 failed。';
COMMENT ON COLUMN import_batch.blocked_count IS '记录级跳过（locked / manual_edited_fields / last_batch_id 不符）时 +1。V2.1 无此列。';

-- -----------------------------------------------------------------------------
-- §5.4 source_record（17 列；业务键五段 C01）
-- -----------------------------------------------------------------------------
CREATE TABLE source_record (
    source_record_id      bigint      GENERATED BY DEFAULT AS IDENTITY,
    dataset_id            text        NOT NULL,
    record_scope          text        NOT NULL,
    external_id           text        NOT NULL,
    parent_external_id    text        NOT NULL,
    duplicate_ordinal     integer     NOT NULL DEFAULT 0,
    raw_file              text        NOT NULL,
    raw_record_index      integer,
    raw_payload           jsonb       NOT NULL,
    content_hash          bytea       NOT NULL,
    first_batch_id        bigint      NOT NULL,
    last_batch_id         bigint,
    is_active             boolean     NOT NULL DEFAULT true,
    inactive_reason       text,
    inactive_at           timestamptz,
    inactive_in_batch_id  bigint,
    ingested_at           timestamptz NOT NULL,

    CONSTRAINT pk_source_record PRIMARY KEY (source_record_id),
    CONSTRAINT fk_source_record_dataset FOREIGN KEY (dataset_id) REFERENCES data_dataset (dataset_id),
    CONSTRAINT fk_source_record_first_batch FOREIGN KEY (first_batch_id) REFERENCES import_batch (batch_id),
    CONSTRAINT fk_source_record_last_batch FOREIGN KEY (last_batch_id) REFERENCES import_batch (batch_id),
    CONSTRAINT fk_source_record_inactive_batch FOREIGN KEY (inactive_in_batch_id) REFERENCES import_batch (batch_id),

    -- C01 五段业务唯一键
    CONSTRAINT uq_source_record_c01 UNIQUE
        (dataset_id, record_scope, parent_external_id, external_id, duplicate_ordinal),

    -- C29 ②：不得空串（哨兵为 '-'，不是 NULL、不是空串）
    CONSTRAINT ck_source_record_parent_not_empty CHECK (parent_external_id <> ''),

    CONSTRAINT ck_source_record_record_scope
        CHECK (record_scope IN ('place', 'name', 'location', 'edge')),

    -- C03 / C18（同一条，双编号不另计）
    CONSTRAINT ck_source_record_c03
        CHECK ((is_active AND inactive_reason IS NULL)
            OR (NOT is_active AND inactive_reason IS NOT NULL)),
    -- C19
    CONSTRAINT ck_source_record_c19
        CHECK (inactive_reason IS NULL
            OR inactive_reason IN ('source_absent', 'batch_rolled_back', 'duplicate_quarantine')),
    -- C20（取代已废除的 C02）
    CONSTRAINT ck_source_record_c20
        CHECK (inactive_reason <> 'duplicate_quarantine' OR duplicate_ordinal > 0),
    -- C21
    CONSTRAINT ck_source_record_c21
        CHECK ((inactive_at IS NULL) = (inactive_reason IS NULL)),
    -- C22
    CONSTRAINT ck_source_record_c22
        CHECK ((inactive_in_batch_id IS NULL) = (inactive_reason IS NULL))
);

COMMENT ON TABLE source_record IS '所有规范化行的追溯终点。失效一律 is_active=false，不 DELETE（§4.6）。';
COMMENT ON COLUMN source_record.parent_external_id IS 'C29 必需段：Pleiades=raw_payload.place_id；MCGD=raw_payload.LocID；无父级写哨兵 ''-''。NOT NULL + 非空串由 ck_source_record_parent_not_empty 保证。哨兵只在导入器中声明一次（设计 C29 ④ 未要求常量表，V2.1.1 固定 9 表，故不新建第 10 张表）。';
COMMENT ON COLUMN source_record.duplicate_ordinal IS '0 = 唯一组；≥1 = 组内名次，按 (content_hash ASC, raw_record_index ASC) 定序。';
COMMENT ON COLUMN source_record.content_hash IS 'sha256(json.dumps(payload, sort_keys=True, ensure_ascii=False, separators=('','','')))；不是 md5（ALG-1：与 issue_fingerprint 算法并存，不可互换）。';
COMMENT ON COLUMN source_record.record_scope IS 'edge 不得写成 connection。';

CREATE INDEX ix_source_record_dataset_external ON source_record (dataset_id, external_id);
CREATE INDEX ix_source_record_content_hash     ON source_record (content_hash);
CREATE INDEX ix_source_record_active_scope     ON source_record (dataset_id, record_scope) WHERE is_active;

-- -----------------------------------------------------------------------------
-- §5.5 historical_place（20 列）
-- -----------------------------------------------------------------------------
CREATE TABLE historical_place (
    place_id                      bigint      GENERATED BY DEFAULT AS IDENTITY,
    dataset_id                    text        NOT NULL,
    grain_key                     text        NOT NULL,
    canonical_name                text        NOT NULL,
    canonical_name_lang           text,
    place_type                    text        NOT NULL DEFAULT 'unknown',
    place_type_source             text        NOT NULL,
    place_type_basis_note         text,
    description                   text,
    record_status                 text        NOT NULL DEFAULT 'staging',
    merged_into_place_id          bigint,
    merge_review_ref              bigint,
    merged_at                     timestamptz,
    created_from_source_record_id bigint,
    created_by                    text        NOT NULL DEFAULT 'import',
    locked                        boolean     NOT NULL DEFAULT false,
    manual_edited_fields          text[]      NOT NULL DEFAULT '{}',
    notes                         text,
    created_at                    timestamptz NOT NULL,
    updated_at                    timestamptz NOT NULL,

    CONSTRAINT pk_historical_place PRIMARY KEY (place_id),
    CONSTRAINT fk_historical_place_dataset FOREIGN KEY (dataset_id) REFERENCES data_dataset (dataset_id),
    CONSTRAINT fk_historical_place_merged_into FOREIGN KEY (merged_into_place_id) REFERENCES historical_place (place_id),
    CONSTRAINT fk_historical_place_created_from FOREIGN KEY (created_from_source_record_id) REFERENCES source_record (source_record_id),
    -- fk_historical_place_merge_review → candidate_match 为循环引用，两表建完后在文件末尾追加

    -- C04
    CONSTRAINT uq_historical_place_c04 UNIQUE (dataset_id, grain_key),
    -- C05
    CONSTRAINT ck_historical_place_c05
        CHECK (created_by = 'manual' OR created_from_source_record_id IS NOT NULL),
    -- C06 合并门禁
    CONSTRAINT ck_historical_place_c06
        CHECK (merged_into_place_id IS NULL
            OR (record_status = 'merged' AND merge_review_ref IS NOT NULL AND merged_at IS NOT NULL)),
    CONSTRAINT ck_historical_place_not_self_merged
        CHECK (merged_into_place_id IS NULL OR merged_into_place_id <> place_id),
    CONSTRAINT ck_historical_place_place_type_source
        CHECK (place_type_source IN ('lev_rank', 'lev_rank_unmapped', 'source_code_unconfirmed', 'unknown', 'manual')),
    CONSTRAINT ck_historical_place_place_type
        CHECK (place_type IN ('admin_center_prefecture', 'admin_center_county', 'admin_center_other', 'settlement', 'unknown')),
    CONSTRAINT ck_historical_place_record_status
        CHECK (record_status IN ('staging', 'rejected', 'merged')),
    CONSTRAINT ck_historical_place_created_by
        CHECK (created_by IN ('import', 'manual')),
    CONSTRAINT ck_historical_place_manual_type_source
        CHECK (place_type_source <> 'manual' OR created_by = 'manual'),
    CONSTRAINT ck_historical_place_lev_rank_type
        CHECK (place_type_source <> 'lev_rank' OR place_type <> 'unknown')
);

COMMENT ON TABLE historical_place IS '地点断言行：不带时间列、不带几何列、不带失效原因（§5.5.1 三条硬规则）。';
COMMENT ON COLUMN historical_place.dataset_id IS 'V2.1 §5.2.1 规则 1「地点不带 dataset 列」已被 Owner 决策 5 推翻；V2.1.1 必带 dataset_id + grain_key。';
COMMENT ON COLUMN historical_place.grain_key IS 'per_record ⇒ external_id；per_parent_external_id ⇒ parent_external_id（§5.5.3）。';
COMMENT ON COLUMN historical_place.record_status IS '3 值 staging/rejected/merged（V2.1 的 published 已作废）。与 name/location 子表值域不同，不得合并（§5.5.2）。';
COMMENT ON COLUMN historical_place.created_from_source_record_id IS '锚点（IDENTITY，永不改写）。与 v_place_evidence.is_canonical_row（当前最佳证据）是两件事（§5.10.4）。';

CREATE INDEX ix_historical_place_merged ON historical_place (merged_into_place_id)
    WHERE merged_into_place_id IS NOT NULL;

