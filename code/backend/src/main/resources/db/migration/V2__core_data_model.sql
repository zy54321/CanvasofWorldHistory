-- §5.6 historical_place_location（33 列）
-- -----------------------------------------------------------------------------
CREATE TABLE historical_place_location (
    location_id           bigint                      GENERATED BY DEFAULT AS IDENTITY,
    place_id              bigint                      NOT NULL,
    source_record_id      bigint,
    geom                  geometry(Geometry, 4326),
    geom_type             text,
    representative_lon    double precision,
    representative_lat    double precision,
    original_x            text,
    original_y            text,
    original_crs          text,
    crs_confidence        text                        NOT NULL,
    axis_order_verified   boolean                     NOT NULL DEFAULT false,
    crs_transform_meta    jsonb,
    location_precision    text                        NOT NULL DEFAULT 'unknown',
    uncertainty_m         integer,
    uncertainty_source    text,
    valid_from_year_astro integer,
    valid_to_year_astro   integer,
    time_bound_type       text                        NOT NULL DEFAULT 'unknown',
    source_beg_rule       smallint,
    source_end_rule       smallint,
    source_time_columns   text                        NOT NULL DEFAULT '',
    time_note             text,
    conflict_status       text                        NOT NULL DEFAULT 'none',
    is_preferred          boolean                     NOT NULL DEFAULT false,
    record_status         text                        NOT NULL DEFAULT 'staging',
    rejected_by           text,
    locked                boolean                     NOT NULL DEFAULT false,
    manual_edited_fields  text[]                      NOT NULL DEFAULT '{}',
    created_by            text                        NOT NULL DEFAULT 'import',
    notes                 text,
    created_at            timestamptz                 NOT NULL,
    updated_at            timestamptz                 NOT NULL,

    CONSTRAINT pk_historical_place_location PRIMARY KEY (location_id),
    CONSTRAINT fk_historical_place_location_place FOREIGN KEY (place_id) REFERENCES historical_place (place_id),
    CONSTRAINT fk_historical_place_location_source_record FOREIGN KEY (source_record_id) REFERENCES source_record (source_record_id),

    -- 枚举域
    CONSTRAINT ck_hpl_geom_type CHECK (geom_type IN ('Point', 'Polygon', 'MultiPolygon')),
    CONSTRAINT ck_hpl_crs_confidence CHECK (crs_confidence IN ('confirmed', 'inferred', 'unknown')),
    CONSTRAINT ck_hpl_location_precision CHECK (location_precision IN ('precise', 'approximate', 'rough', 'unknown')),
    CONSTRAINT ck_hpl_time_bound_type CHECK (time_bound_type IN ('exact', 'bounded', 'exact_or_bounded', 'tpq_taq', 'derived_tpq_taq', 'snapshot', 'unknown')),
    CONSTRAINT ck_hpl_conflict_status CHECK (conflict_status IN ('none', 'disputed', 'arbitrated')),
    -- 子表 record_status 3 值（含 published，与地点表的 merged 值域不同）
    CONSTRAINT ck_hpl_record_status CHECK (record_status IN ('staging', 'published', 'rejected')),
    CONSTRAINT ck_hpl_created_by CHECK (created_by IN ('import', 'manual')),

    -- C14 CRS 门禁
    CONSTRAINT ck_hpl_c14 CHECK (crs_confidence <> 'unknown' OR record_status <> 'published'),
    -- C15 几何门禁
    CONSTRAINT ck_hpl_c15 CHECK (geom IS NOT NULL OR record_status <> 'published'),
    -- C16
    CONSTRAINT ck_hpl_c16 CHECK (time_bound_type <> 'exact'
        OR (valid_from_year_astro IS NOT NULL AND valid_to_year_astro IS NOT NULL)),
    -- C25 / C26
    CONSTRAINT ck_hpl_c25 CHECK ((record_status = 'rejected') = (rejected_by IS NOT NULL)),
    CONSTRAINT ck_hpl_c26 CHECK (rejected_by IS NULL OR rejected_by IN ('auto', 'manual')),
    -- C13（改名后：source_time_columns 与数字规则码互斥）
    CONSTRAINT ck_hpl_c13 CHECK (source_time_columns = '' OR (source_beg_rule IS NULL AND source_end_rule IS NULL)),
    -- 其余表级 CHECK
    CONSTRAINT ck_hpl_preferred_not_disputed CHECK (NOT is_preferred OR conflict_status <> 'disputed'),
    CONSTRAINT ck_hpl_manual_needs_manual_created_by CHECK (source_record_id IS NOT NULL OR created_by = 'manual'),
    CONSTRAINT ck_hpl_geom_matches_type
        CHECK (geom IS NULL OR ST_GeometryType(geom) = 'ST_' || geom_type)
);

COMMENT ON TABLE historical_place_location IS '位置行：几何、CRS、时间都在这张表上。';
COMMENT ON COLUMN historical_place_location.geom IS 'EPSG:4326。10 条 CHGIS 坐标为 ********** （DBF 溢出）⇒ NULL。GiST 索引见下。';
COMMENT ON COLUMN historical_place_location.original_x IS '必须 text：********** 转 numeric 就丢。';
COMMENT ON COLUMN historical_place_location.crs_confidence IS '只能由 original_crs 派生：EPSG:4326→confirmed；unknown/NULL→unknown；人工可上调为 inferred。';
COMMENT ON COLUMN historical_place_location.source_time_columns IS 'V2.1 名 source_rule_vocabulary，本版改名。语义=该行来源文件声明了哪些时间列（列级掩码），逐字保留，不是本行实际使用的规则。';
COMMENT ON COLUMN historical_place_location.is_preferred IS '导入器永不置 true。';
COMMENT ON COLUMN historical_place_location.valid_from_year_astro IS '倒挂的 28 条留空，不交换不夹取。天文纪年：公元前 1 年 = 0。';

-- C07：一个源记录最多派生一条位置行（部分唯一索引）
CREATE UNIQUE INDEX uq_hpl_c07 ON historical_place_location (source_record_id)
