    CONSTRAINT fk_historical_place_name_place FOREIGN KEY (place_id) REFERENCES historical_place (place_id),
    CONSTRAINT fk_historical_place_name_source_record FOREIGN KEY (source_record_id) REFERENCES source_record (source_record_id),

