-- -----------------------------------------------------------------------------
-- §4.5 issue_fingerprint 的施工适配（唯一一处偏离字面写法的实现细节）
--
-- 设计要求：GENERATED ALWAYS AS md5(jsonb_build_array(a,b,c,d,e,f)::text) STORED
-- 实测：PostgreSQL 17 把 jsonb_build_array 标记为 STABLE（provolatile='s'），
--       STORED 生成列要求表达式 IMMUTABLE，字面写法被 PG 直接拒绝（SQLSTATE 42P17）。
-- 处置：把同一表达式封装为 IMMUTABLE 函数，生成列调用该函数。
--       入参只有 bigint/text，函数输出对相同输入恒定 ⇒ 语义与设计逐字一致
--       （V2.1.1 已用「六段 JSON 数组」定死格式，本封装不改变任何一段、不改变分隔符）。
-- 证据：V2 迁移验证时以 md5(jsonb_build_array(...)::text) 直算值与生成列值逐条比对，必须完全相等。
-- -----------------------------------------------------------------------------
CREATE FUNCTION fn_issue_fingerprint(
    p_source_record_id bigint,
    p_dataset_id       text,
    p_place_id         bigint,
    p_issue_type       text,
    p_field_name       text,
    p_observed_value   text
) RETURNS text
LANGUAGE sql
IMMUTABLE
PARALLEL SAFE
AS $$
    SELECT md5(jsonb_build_array(
               p_source_record_id, p_dataset_id, p_place_id,
               p_issue_type, p_field_name, p_observed_value)::text)
$$;

COMMENT ON FUNCTION fn_issue_fingerprint(bigint, text, bigint, text, text, text)
    IS '§4.5 台账指纹六段 md5：source_record_id, dataset_id, place_id, issue_type, field_name, observed_value（不含 batch_id）。封装为 IMMUTABLE 仅为满足生成列要求，算法与分段不变。';

